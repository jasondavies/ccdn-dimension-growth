#!/usr/bin/env python3
"""Generate docs/modules.md and docs/statements.md from the sources and the completion audit.

docs/modules.md lists every library module by directory, with the first sentence of its module
docstring. docs/statements.md tabulates the audited statements of the paper recorded in
docs/completion-audit.json. `--check` fails when either file is out of date.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = ROOT / "docs" / "modules.md"
STATEMENTS = ROOT / "docs" / "statements.md"
AUDIT = ROOT / "docs" / "completion-audit.json"

DIRECTORIES = {
    "": "Main results",
    "Algebra": "Polynomial and commutative-algebra lemmas",
    "Analysis": "Real and prime-number estimates",
    "Auxiliary": "Auxiliary polynomials, positioning and bad primes (Sections 3.1, 3.3, 3.4, 4.2)",
    "Center": "Chow forms, good centers and Plücker equations (Section 5)",
    "ClassGroup": "Two-torsion in class groups (Theorem 6)",
    "Counterexample": "Counterexamples to printed intermediate statements",
    "Curve": "Curves (Theorems 2 and 3)",
    "Determinant": "Local and global determinant estimates (Sections 2 and 3.2)",
    "ForMathlib": "General results suitable for Mathlib",
    "Height": "Heights, boxes and projective points",
    "Hilbert": "Hilbert functions, dimension and degree",
    "Hypersurface": "Hyperplane slicing and hypersurface counts (Sections 4.1, 4.3)",
    "LowerBound": "Lower bounds (Proposition 5, Section 6)",
    "Noether": "Noether irreducibility forms (Theorem 3.2.2)",
    "Plane": "Plane curves",
    "Projection": "Projections and normalizations (Propositions 4.3.1, 4.3.2)",
    "Surface": "Surfaces (Propositions 4.3.3, 4.3.4, Theorem 4.3.5)",
}


def first_sentence(path: Path) -> str:
    match = re.search(r"/-!(.*?)-/", path.read_text(encoding="utf-8"), re.S)
    if match is None:
        return ""
    text = " ".join(line.strip() for line in match.group(1).splitlines()
                    if line.strip() and not line.strip().startswith("#"))
    sentence = re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0]
    return sentence.replace("|", "\\|")


def render_modules() -> str:
    groups: dict[str, list[Path]] = {}
    for path in sorted((ROOT / "CCDN").rglob("*.lean")):
        directory = "/".join(path.relative_to(ROOT / "CCDN").parts[:-1])
        groups.setdefault(directory, []).append(path)
    unknown = sorted(set(groups) - set(DIRECTORIES))
    if unknown:
        raise SystemExit(f"Describe these directories in scripts/update-docs.py: {unknown}")
    lines = ["# Modules", "",
             "Generated by `scripts/update-docs.py` from the module docstrings.", ""]
    for directory in sorted(groups, key=lambda name: (name != "", name)):
        title = f"`CCDN/{directory}/`" if directory else "`CCDN/`"
        lines += [f"## {title}: {DIRECTORIES[directory]}", "", "| Module | Content |",
                  "| --- | --- |"]
        for path in groups[directory]:
            module = ".".join(path.relative_to(ROOT).with_suffix("").parts)
            relative = path.relative_to(ROOT / "docs", walk_up=True)
            lines.append(f"| [`{module}`]({relative}) | {first_sentence(path)} |")
        lines.append("")
    return "\n".join(lines)


def render_statements() -> str:
    audit = json.loads(AUDIT.read_text(encoding="utf-8"))
    evidence = {item["id"]: item for item in audit["evidence"]}
    lines = ["# Audited statements", "",
             "Generated by `scripts/update-docs.py` from `docs/completion-audit.json`, which "
             "records the full scope notes. Statuses: `matched` (as printed), `stronger`, "
             "`corrected` (printed form false or amended; corrected form proved), `refuted` "
             "(printed form formally refuted; replacement proved).", "",
             "| Paper | Status | Lean declarations |", "| --- | --- | --- |"]
    short = {
        "statement_matched": "matched",
        "statement_matched_in_coordinate_model": "matched (coordinate model)",
        "statement_matched_by_composition": "matched (by composition)",
        "stronger_statement_matched": "stronger",
        "corrected_statement_matched": "corrected",
        "literal_refuted_replacement_matched": "refuted",
    }
    for requirement in audit["requirements"]:
        names = []
        for ref in requirement["evidence_refs"]:
            item = evidence.get(ref)
            if item is not None:
                file = item["file"]
                link = file if file.startswith(".lake") else f"../{file}"
                names.append(f"[`{item['declaration'].removeprefix('CCDN.')}`]({link}#L{item['line']})")
        status = short.get(requirement["statement_status"], requirement["statement_status"])
        lines.append(f"| {requirement['source_label']} | {status} | {', '.join(names)} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the files are stale")
    check = parser.parse_args().check
    stale = []
    for target, text in ((MODULES, render_modules()), (STATEMENTS, render_statements())):
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(text, encoding="utf-8")
    if stale:
        print(f"Out of date: {', '.join(stale)}; run scripts/update-docs.py")
        return 1
    if check:
        print("Generated documentation is current.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
